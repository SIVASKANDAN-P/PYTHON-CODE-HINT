def generate_response(prompt,lora,tokeniser,model):
  '''
  Generating response from teh model. The Lora parameter is a binary value to activate
  or deactivate trained lora adopters.
  '''
  if lora:
    model.enable_adapter_layers()
  else:
    model.disable_adapter_layers()
  loaded_tokenizer = tokeniser

  # max_input_length = model.config.max_position_embeddings
  max_input_length = 1000
  # print(max_input_length)

  inputs = loaded_tokenizer(prompt, return_tensors="pt",truncation=True, padding=True, max_length=max_input_length,add_special_tokens=True).to(model.device)

  # Generate predictions
  generated_ids = model.generate(**inputs,max_new_tokens=2000)

  # Decode the generated output
  generated_text = loaded_tokenizer.decode(generated_ids[0], skip_special_tokens=True)

  print(generated_text)
  return generated_text



