def code(text):
  '''
  Extracting code from generated response using predefined python token.
  '''
  mat = re.search(r"<prompt_end>\n(.*)", text, re.DOTALL)
  #print(mat)
  if mat:
    resp = mat.group(1)
    #print(resp)
    mat1 = re.search(r"```python\n(.*)```", resp, re.DOTALL)
    mat2 = re.search(r"'''python\n(.*)'''", resp, re.DOTALL)
    if mat1:
      python_code = mat.group(1)
      return python_code
    elif mat2:
      python_code = mat2.group(1)
      return python_code
    else:
      return 0
  else:
    return 0

def ins(text):
  '''
  Extracting only the instruction from the model generated response.
  '''
  mat = re.search(r"<prompt_end>\n(.*)", text, re.DOTALL)
  #print(mat)
  if mat:
    resp = mat.group(1)
    mat1 = re.search(r"### Response:(\s*?)\n(.*)```python", resp, re.DOTALL)
    mat2 = re.search(r"Response:\n(.*)", resp, re.DOTALL)
    #print(mat)
    if mat1:
      inst = mat.group(1)
      return inst
    elif mat2:
      inst = mat2.group(1)
      return inst
    else:
      return 0
  else:
    return 0

def ans(text):
  '''
  Extracting only text generated by model after removing the input prompt from
  model generation using <prompt_end> tag.
  '''
  mat = re.search(r"<prompt_end>\n(.*)", text, re.DOTALL)
  #print(mat)
  if mat:
    return mat.group(1)
  else:
    return 0

